#!/usr/bin/env node
/**
 * Generates prisma/schema.test.prisma: a SQLite mirror of the production
 * PostgreSQL schema, so the Jest/Supertest suite runs without Docker/Postgres.
 *
 * Transformations (test-only, never shipped):
 *  - datasource provider -> sqlite, url from TEST_DATABASE_URL
 *  - separate generated client (generated/test-client) so the Postgres client
 *    used by production code stays intact
 *  - native type attributes (e.g. @db.Text) -> stripped (unsupported by SQLite)
 *  - enum blocks -> removed; enum-typed fields -> String. The allowed values are
 *    still enforced at runtime by Zod (src/domain/enums.ts) and by CHECK
 *    constraints in the PostgreSQL migration.
 *
 * Anything the transform does not understand fails loudly rather than silently
 * producing a schema that drifts from production.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'prisma', 'schema.prisma');
const targetPath = path.join(root, 'prisma', 'schema.test.prisma');

const source = fs.readFileSync(sourcePath, 'utf8');

const enumNames = [...source.matchAll(/^enum\s+(\w+)\s*\{/gm)].map((m) => m[1]);
if (enumNames.length === 0) throw new Error('No enum blocks found in schema.prisma');
const enumSet = new Set(enumNames);

/** Enum member names, so `@default(PENDING)` can become `@default("PENDING")`. */
const enumValues = new Set();
for (const block of source.matchAll(/^enum\s+\w+\s*\{([\s\S]*?)^\}/gm)) {
  for (const line of block[1].split('\n')) {
    const value = line.trim().split(/\s+/)[0];
    if (value && !value.startsWith('//')) enumValues.add(value);
  }
}

// 1. Strip enum blocks (and their trailing blank line).
let out = source.replace(/^enum\s+\w+\s*\{[\s\S]*?^\}\n?/gm, '');

// 2. Swap datasource + generator.
out = out.replace(
  /datasource\s+db\s*\{[\s\S]*?\}/m,
  'datasource db {\n  provider = "sqlite"\n  url      = env("TEST_DATABASE_URL")\n}',
);
out = out.replace(
  /generator\s+client\s*\{[\s\S]*?\}/m,
  'generator client {\n  provider = "prisma-client-js"\n  output   = "../generated/test-client"\n}',
);

// 3. Native type attributes are Postgres-only.
out = out.replace(/\s+@db\.\w+(\([^)]*\))?/g, '');

// 4. Line-based enum-field rewrite: `  fieldName  EnumType?  @attrs`.
const fieldLine = /^(\s*\w+\s+)(\w+)(\[\])?(\?)?(\s+.*|\s*)$/;
const rewritten = out.split('\n').map((line) => {
  const m = line.match(fieldLine);
  if (!m) return line;
  const [, prefix, typeName, list = '', optional = '', rest = ''] = m;
  if (!enumSet.has(typeName)) return line;
  return `${prefix}String${list}${optional}${rest}`;
});
out = rewritten.join('\n');

// 4b. Enum member defaults must become string literals on SQLite.
out = out.replace(/@default\((\w+)\)/g, (match, value) =>
  enumValues.has(value) ? `@default("${value}")` : match,
);

// 5. Fail loudly on any residue.
if (/@db\./.test(out)) throw new Error('Unstripped native type attribute in generated test schema');
const leak = new RegExp(`(^|[^\\w])(${enumNames.join('|')})([^\\w]|$)`, 'm');
const leakMatch = out.match(leak);
if (leakMatch) {
  const idx = out.indexOf(leakMatch[0]);
  console.error(out.slice(Math.max(0, idx - 160), idx + 80));
  throw new Error(`Enum reference "${leakMatch[2]}" leaked into generated test schema`);
}

const header =
  '// AUTO-GENERATED by scripts/gen-test-schema.cjs - do not edit, do not commit.\n' +
  '// SQLite mirror of prisma/schema.prisma used only by the test suite.\n\n';

fs.writeFileSync(targetPath, header + out, 'utf8');
console.log(
  `[gen-test-schema] wrote ${path.relative(root, targetPath)} (${enumNames.length} enums flattened)`,
);
